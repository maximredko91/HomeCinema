package com.homecinema.library.data.search

/**
 * Russian -> English word translations for #hashtag tag search. .nfo `<tag>` values (TMDb-style
 * keywords, as scraped by Kodi/Radarr/Sonarr) are always in English, so a Russian query needs
 * translating before it can match anything - without this, "#пираты" would never find a tag
 * literally stored as "pirates". See [matchesTagQuery] for how this gets used.
 *
 * Backed by `src/main/resources/dictionaries/ru_en_tag_dictionary.tsv` (one `ru<TAB>en1,en2,...`
 * line per headword, ~40k Russian words) rather than a Kotlin list literal - a first attempt
 * hand-typed ~800 words curated from a one-time dump of this library's actual tag vocabulary,
 * but that missed plenty of completely ordinary words (e.g. "рыцарь"/knight, "вампир"/vampire)
 * that just hadn't shown up in that particular snapshot, and would keep missing whatever's not
 * in the current library as it grows. Bundling the file as a Java/Kotlin *resource* (not an
 * Android asset) means it loads the same way via the classloader both on-device and in a plain
 * JVM unit test (see LibraryFilteringTest) - no Context/AssetManager needed, so this dictionary
 * and [matchesTagQuery] stay pure/injection-free.
 *
 * Source: the FreeDict rus-eng dictionary (freedict.org), auto-generated by WikDict from
 * Wiktionary.org, ~42,600 headwords - filtered down to single-word Russian headwords with
 * short/plain English translations (drops multi-word Russian phrases and long English glosses,
 * which don't fit this word-by-word matching scheme anyway) and merged with the original
 * hand-curated pairs. Licensed CC BY-SA 3.0 - attribution is in Settings -> О приложении ->
 * "Лицензии открытого кода".
 */
private val dictionaryResourcePath = "dictionaries/ru_en_tag_dictionary.tsv"

/** Merges every English candidate for a given Russian word into a list - a handful of Russian
 * words have several natural English translations (e.g. "рука" -> both "hand" and "arm"). */
val RU_EN_TAG_DICTIONARY: Map<String, List<String>> by lazy {
    val stream = object {}.javaClass.classLoader?.getResourceAsStream(dictionaryResourcePath)
        ?: return@lazy emptyMap()
    stream.bufferedReader(Charsets.UTF_8).useLines { lines ->
        lines.mapNotNull { line ->
            val tab = line.indexOf('\t')
            if (tab < 0) return@mapNotNull null
            val ru = line.substring(0, tab)
            val en = line.substring(tab + 1).split(',').filter { it.isNotBlank() }
            if (en.isEmpty()) null else ru to en
        }.toMap()
    }
}

/**
 * True if [tags] (a comma-separated `MediaItemEntity.tags` string) matches [rawQuery] - tries
 * the query as-is first (covers an already-English query, or the rare case a tag actually is in
 * Russian), then falls back to translating every word of the query via
 * [RU_EN_TAG_DICTIONARY] and requiring the SAME tag to contain a translated candidate for every
 * word. Word-by-word (rather than translating the whole phrase at once) so multi-word queries
 * don't need to match the tag's exact word order, and so one untranslatable word among several
 * doesn't sink the whole query.
 */
fun matchesTagQuery(tags: String, rawQuery: String): Boolean {
    val query = rawQuery.trim()
    if (query.isEmpty()) return false
    val tagList = tags.split(",").map { it.trim() }.filter { it.isNotEmpty() }

    if (tagList.any { it.contains(query, ignoreCase = true) }) return true

    val queryWords = query.lowercase().split(Regex("\\s+")).filter { it.isNotBlank() }
    val candidatesPerWord = queryWords.map { word -> RU_EN_TAG_DICTIONARY[word].orEmpty() }
    if (candidatesPerWord.any { it.isEmpty() }) return false

    return tagList.any { tag ->
        candidatesPerWord.all { candidates -> candidates.any { tag.contains(it, ignoreCase = true) } }
    }
}
