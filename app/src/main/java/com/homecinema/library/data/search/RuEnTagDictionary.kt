/** Merges [RU_EN_PAIRS] into the real lookup structure - one Russian word may point at
 * several English candidate words. */
val RU_EN_TAG_DICTIONARY: Map<String, List<String>> =
    RU_EN_PAIRS.groupBy({ it.first }, { it.second }).mapValues { it.value.distinct() }

/**
 * True if [tags] (a comma-separated `MediaItemEntity.tags` string) matches [rawQuery] - tries
 * the query as-is first (covers an already-English query, or the rare case a tag actually is in
 * Russian), then falls back to translating every word of the query via
 * [RU_EN_TAG_DICTIONARY] and requiring the SAME tag to contain a translated candidate for every
 * word. Word-by-word (rather than translating the whole phrase at once) so multi-word queries
 * don't need to match the tag's exact word order, and so one untranslatable word among several
 * doesn't sink the whole query.
 */
fun matchesTagQuery(tags: String, rawQuery: String): Boolean {
    val query = rawQuery.trim()
    if (query.isEmpty()) return false
    val tagList = tags.split(",").map { it.trim() }.filter { it.isNotEmpty() }

    if (tagList.any { it.contains(query, ignoreCase = true) }) return true

    val queryWords = query.lowercase().split(Regex("\\s+")).filter { it.isNotBlank() }
    val candidatesPerWord = queryWords.map { word -> RU_EN_TAG_DICTIONARY[word].orEmpty() }
    if (candidatesPerWord.any { it.isEmpty() }) return false

    return tagList.any { tag ->
        candidatesPerWord.all { candidates -> candidates.any { tag.contains(it, ignoreCase = true) } }
    }
}
